function normalizeLanguage(value) {
  const full = String(value ?? "").trim().toLowerCase().replaceAll("_", "-");
  // Home Assistant exposes Simplified and Traditional Chinese as distinct
  // BCP47 locales. Lotus deliberately ships Simplified Chinese only:
  // do not silently display Simplified Chinese to a zh-Hant user.
  if (full === "zh-hant" || full.startsWith("zh-hant-") || full === "zh-tw" || full.startsWith("zh-tw-") || full === "zh-hk" || full.startsWith("zh-hk-")) {
    return "en";
  }
  if (full === "zh-hans" || full.startsWith("zh-hans-") || full === "zh-cn" || full.startsWith("zh-cn-") || full === "zh-sg" || full.startsWith("zh-sg-")) {
    return "zh";
  }
  const raw = full.split("-")[0];
  return SUPPORTED.has(raw) ? raw : "en";
}

export function lotusDebug(...args) {
  let enabled = globalThis.LotusVisualDebug === true;
  if (!enabled) {
    try {
      enabled = globalThis.localStorage?.getItem?.("lotus_view_studio.debug") === "1"
        || globalThis.localStorage?.getItem?.("lotus_visual.debug") === "1";
    } catch (_error) {
      // Storage can be disabled by the browser; diagnostics must remain optional.
    }
  }
  if (!enabled) return;
  globalThis.console?.debug?.("[Lotus View Studio]", ...args);
}

function detectHassLanguage(hass = currentHass) {
  const raw = hass?.locale?.language ?? hass?.language ??
    (typeof document !== "undefined" ? document.documentElement?.lang : "") ??
    (typeof navigator !== "undefined" ? navigator.language : "en");
  return normalizeLanguage(raw);
}

function resolveCurrentLanguage() {
  return preference === "auto" ? detectHassLanguage() : normalizeLanguage(preference);
}

function emitLanguageChanged(previous) {
  const next = currentLanguage;
  if (previous === next) return;
  const detail = { language: next, preference, automaticLanguage: detectHassLanguage() };
  for (const listener of [...listeners]) {
    try { listener(detail); } catch (error) { lotusDebug("i18n listener failed", error); }
  }
  globalThis.dispatchEvent?.(new CustomEvent("lotus-language-changed", { detail }));
}

function setResolvedLanguage() {
  const previous = currentLanguage;
  currentLanguage = resolveCurrentLanguage();
  emitLanguageChanged(previous);
}

function storageKey(hass) {
  const id = hass?.user?.id || "anonymous";
  return `lotus_view_studio.language.${id}`;
}

function legacyStorageKey(hass) {
  const id = hass?.user?.id || "anonymous";
  return `lotus_visual.language.${id}`;
}

async function loadPreference(hass) {
  const userId = hass?.user?.id || "anonymous";
  if (loadedUserId === userId) return;
  loadedUserId = userId;
  const generation = ++loadGeneration;

  let local = "auto";
  try {
    local = localStorage.getItem(storageKey(hass)) || localStorage.getItem(legacyStorageKey(hass)) || "auto";
    if (local !== "auto" && !localStorage.getItem(storageKey(hass))) {
      localStorage.setItem(storageKey(hass), local);
    }
  } catch (_error) {
    local = "auto";
  }
  if (LANGUAGE_MODES.has(local)) {
    preference = local;
    setResolvedLanguage();
  }

  if (!hass?.callWS) return;
  try {
    const result = await hass.callWS({ type: "lotus_view_studio/preferences/get" });
    if (generation !== loadGeneration) return;
    const mode = String(result?.language || "auto");
    const beforeServerLanguage = currentLanguage;
    preference = LANGUAGE_MODES.has(mode) ? mode : "auto";
    try { localStorage.setItem(storageKey(hass), preference); } catch (_error) {}
    setResolvedLanguage();
    // A preference stored on the server may be discovered on a new browser
    // after components have already rendered once. Reload only when the
    // resolved language actually changes; the freshly cached local preference
    // prevents any reload loop.
    if (currentLanguage !== beforeServerLanguage && typeof window !== "undefined" && window.location?.reload) {
      queueMicrotask(() => window.location.reload());
    }
  } catch (error) {
    lotusDebug("Unable to load language preference; using local fallback.", error);
  }
}

export function lotusSetHass(hass) {
  currentHass = hass || currentHass;
  setResolvedLanguage();
  if (hass) void loadPreference(hass);
  return currentLanguage;
}

export async function lotusSetLanguagePreference(hass, mode) {
  const next = String(mode || "auto");
  if (!LANGUAGE_MODES.has(next)) throw new Error(`Unsupported Lotus View Studio language: ${next}`);
  currentHass = hass || currentHass;
  preference = next;
  try { localStorage.setItem(storageKey(currentHass), next); } catch (_error) {}
  setResolvedLanguage();

  if (currentHass?.callWS) {
    const result = await currentHass.callWS({ type: "lotus_view_studio/preferences/set", language: next });
    const saved = String(result?.language || next);
    if (LANGUAGE_MODES.has(saved)) preference = saved;
    try { localStorage.setItem(storageKey(currentHass), preference); } catch (_error) {}
    setResolvedLanguage();
  }
  return { preference, language: currentLanguage, automaticLanguage: detectHassLanguage(currentHass) };
}

