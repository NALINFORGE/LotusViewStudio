export function lotusSubscribeLanguage(listener) {
  if (typeof listener !== "function") return () => {};
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function applyDynamic(source, lang) {
  for (const [pattern, formatter] of DYNAMIC[lang] || []) {
    const match = source.match(pattern);
    if (match) return formatter(...match);
  }
  return null;
}

function applyFallback(source, lang) {
  let translated = source;
  const replacements = FALLBACK_REPLACEMENTS[lang] || LOTUS_EXTRA_REPLACEMENTS[lang] || LOTUS_EUROPE_REPLACEMENTS[lang] || [];
  for (const [from, to] of replacements) {
    translated = translated.split(from).join(to);
  }
  return translated;
}

function applyExtraFallback(source, lang) {
  let translated = source;
  let covered = 0;
  for (const [from, to] of LOTUS_EXTRA_REPLACEMENTS[lang] || LOTUS_EUROPE_REPLACEMENTS[lang] || []) {
    const occurrences = translated.split(from).length - 1;
    if (!occurrences) continue;
    covered += from.length * occurrences;
    translated = translated.split(from).join(to);
  }
  return { translated, coverage: source.length ? Math.min(1, covered / source.length) : 1 };
}

function englishFallback(source) {
  return EXACT_EN[source] ?? applyDynamic(source, "en") ?? applyFallback(source, "en") ?? source;
}

export function lotusT(value, vars = undefined, forcedLanguage = undefined) {
  if (value === null || value === undefined) return "";
  const source = String(value);
  const lang = forcedLanguage ? normalizeLanguage(forcedLanguage) : currentLanguage;
  let translated = source;
  if (lang === "en") translated = EXACT_EN[source] ?? applyDynamic(source, "en") ?? applyFallback(source, "en");
  else if (lang === "de") translated = EXACT_DE[source] ?? applyDynamic(source, "de") ?? applyFallback(source, "de");
  else if (lang === "fr") translated = EXACT_FR_FROM_EN[source] ?? source;
  else {
    const exact = LOTUS_EXTRA_EXACT[lang]?.[source] ?? LOTUS_EUROPE_EXACT[lang]?.[source];
    if (exact !== undefined) translated = exact;
    else {
      const { translated: candidate, coverage } = applyExtraFallback(source, lang);
      // Do not expose a half-translated French label. Additional languages
      // only accept phrase replacement when most of the source was covered;
      // otherwise English is the deterministic safety fallback.
      translated = candidate !== source && coverage >= 0.55 ? candidate : englishFallback(source);
    }
  }
  if (vars && typeof vars === "object") {
    translated = translated.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key) =>
      vars[key] === undefined ? match : String(vars[key])
    );
  }
  return translated;
}

export function lotusLocalizeSelector(selector) {
  if (!selector || typeof selector !== "object") return selector;
  const cloned = typeof structuredClone === "function" ? structuredClone(selector) : JSON.parse(JSON.stringify(selector));
  const walk = (node) => {
    if (!node || typeof node !== "object") return;
    if (Array.isArray(node)) {
      for (const item of node) walk(item);
      return;
    }
    if (Array.isArray(node.options)) {
      node.options = node.options.map((option) => {
        if (typeof option !== "string") return option;
        const labels = SELECTOR_VALUE_LABELS[option];
        const extraLabel = LOTUS_EXTRA_SELECTOR_LABELS[option]?.[currentLanguage]
          || LOTUS_EUROPE_SELECTOR_LABELS[option]?.[currentLanguage];
        if (!labels && !extraLabel) return option;
        return { value: option, label: labels?.[currentLanguage] || extraLabel || labels?.en || option };
      });
    }
    if (typeof node.label === "string") node.label = lotusT(node.label);
    for (const value of Object.values(node)) walk(value);
  };
  walk(cloned);
  return cloned;
}

export function lotusGetTextDirection(language = currentLanguage) {
  return LOTUS_RTL_LANGUAGES.has(normalizeLanguage(language)) ? "rtl" : "ltr";
}

export function lotusIsRtl(language = currentLanguage) {
  return lotusGetTextDirection(language) === "rtl";
}

export function lotusLanguageLabel(mode, displayLanguage = currentLanguage) {
  const item = LOTUS_LANGUAGES.find((entry) => entry.value === mode) || LOTUS_LANGUAGES[0];
  if (mode === "auto") return lotusT("Automatique — Home Assistant", undefined, displayLanguage);
  return item.nativeName;
}

